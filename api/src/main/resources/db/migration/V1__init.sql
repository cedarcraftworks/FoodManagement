-- 団体。データは団体ごとに分かれ、他の団体のデータには触れられない
CREATE TABLE organizations (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                        VARCHAR(200) NOT NULL,
    include_expired_best_before BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- スタッフ（役割：ADMIN = 管理者、STAFF = スタッフ）
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    email           VARCHAR(254) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    role            VARCHAR(10)  NOT NULL CHECK (role IN ('ADMIN', 'STAFF')),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ログイン中のトークン（トークンそのものではなく SHA-256 のハッシュだけを保存）
CREATE TABLE sessions (
    token_hash CHAR(64)    PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

-- 商品。JAN コードがあれば、団体の中で 1 つにまとめる
CREATE TABLE items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    jan             VARCHAR(13),
    name            VARCHAR(200) NOT NULL,
    category        VARCHAR(20)  NOT NULL
);
CREATE UNIQUE INDEX items_organization_jan ON items (organization_id, jan) WHERE jan IS NOT NULL;

-- 在庫（ロット）。同じ商品でも期限が違えば別の在庫として扱う
CREATE TABLE lots (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    item_id         BIGINT       NOT NULL REFERENCES items (id),
    quantity        INT          NOT NULL CHECK (quantity >= 0),
    expires_on      DATE         NOT NULL,
    expiry_type     VARCHAR(12)  NOT NULL CHECK (expiry_type IN ('best_before', 'use_by')),
    received_on     DATE         NOT NULL,
    donor           VARCHAR(200),
    -- 楽観的ロックの版番号。更新のたびに 1 増やす
    version         INT          NOT NULL DEFAULT 0
);
CREATE INDEX lots_organization_expires ON lots (organization_id, expires_on);

-- 入出庫の履歴。在庫の数を変えるときは必ず同じトランザクションで 1 行追加する
CREATE TABLE movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    lot_id          BIGINT       NOT NULL REFERENCES lots (id),
    kind            VARCHAR(12)  NOT NULL CHECK (kind IN ('receive', 'distribute', 'dispose')),
    quantity        INT          NOT NULL CHECK (quantity > 0),
    user_id         BIGINT       NOT NULL REFERENCES users (id),
    occurred_on     DATE         NOT NULL,
    note            VARCHAR(500),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX movements_organization_occurred ON movements (organization_id, occurred_on);
